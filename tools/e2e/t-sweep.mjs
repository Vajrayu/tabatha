import { launch, S } from './lib.mjs';
const T = await launch(process.env.EXT);
const ev = (fn, arg) => T.sw.evaluate(fn, arg);
const [a, b] = await T.open(['alpha', 'beta']);
await T.skipFirstRun();
// four tabs that are loaded in the background and never looked at
for (const n of ['gamma', 'delta', 't1', 't2']) await ev(async (u) => { await chrome.tabs.create({ url: u, active: false }); }, T.url(n));
await ev(() => new Promise((r) => setTimeout(r, 1500)));
await b.bringToFront(); await b.waitForTimeout(900);
const previews = () => ev(() => chrome.storage.local.get('pvidx').then((o) => Object.keys(o.pvidx || {}).map((u) => u.split('/').pop())));
const mru = () => ev(() => chrome.storage.session.get('mru').then((o) => o.mru));
const active = () => ev(async () => (await chrome.tabs.query({ active: true, lastFocusedWindow: true }))[0].title);
const before = await previews();
T.log('background tabs start without previews', !before.includes('gamma.html') && !before.includes('t2.html'), before.join());
await T.tap(b);
const f = () => T.frame(b);
await b.waitForTimeout(500);
const label = await f().$eval('#sweep-btn', (n) => (n.hidden ? '(hidden)' : n.textContent));
T.log('capture button offered with a count', /\d+ without preview · Capture all/.test(label), label);
const mruBefore = await mru(); const actBefore = await active();
await f().click('#sweep-btn');
await b.waitForTimeout(500);
T.log('switcher closes when the sweep starts', !(await T.isOpen(b)));
const popup = T.ctx.pages().find((p) => p.url().includes('sweep.html'));
T.log('progress window opens', !!popup);
if (popup) await popup.screenshot({ path: S + '/shot-sweep.png' });
await ev(() => new Promise((r) => setTimeout(r, 9000)));
const after = await previews();
T.log('every tab now has a preview', ['alpha.html', 'beta.html', 'gamma.html', 'delta.html', 't1.html', 't2.html'].every((x) => after.includes(x)), after.join());
T.log('same tab is showing as before', (await active()) === actBefore, await active());
T.log('most-recently-used order untouched', JSON.stringify(await mru()) === JSON.stringify(mruBefore), JSON.stringify([mruBefore, await mru()]));
T.log('progress window is gone', !T.ctx.pages().some((p) => p.url().includes('sweep.html')));
const st = await ev(() => chrome.storage.session.get('sweep').then((o) => o.sweep));
T.log('sweep state reset', st && st.running === false, JSON.stringify(st));
await T.tap(b); await b.waitForTimeout(500);
T.log('button gone when nothing is missing', await f().$eval('#sweep-btn', (n) => n.hidden));
await T.close();
