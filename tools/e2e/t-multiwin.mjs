// Two windows: window chips, Alt+W, and a sweep that puts each window back on its own tab.
import { launch } from './lib.mjs';
const T = await launch(process.env.EXT);
const ev = (fn, arg) => T.sw.evaluate(fn, arg);
const wait = (ms) => ev((m) => new Promise((r) => setTimeout(r, m)), ms);
const [a] = await T.open(['alpha']); await T.skipFirstRun();
await ev(async (u) => { await chrome.tabs.create({ url: u[0], active: false }); await chrome.tabs.create({ url: u[1], active: false }); }, [T.url('beta'), T.url('gamma')]);
const w2 = await ev(async (u) => { const w = await chrome.windows.create({ url: u[0], focused: false }); await chrome.tabs.create({ windowId: w.id, url: u[1], active: false }); await chrome.tabs.create({ windowId: w.id, url: u[2], active: false }); return w.id; }, [T.url('delta'), T.url('t1'), T.url('t2')]);
await wait(1800);
const actives = () => ev(async () => (await chrome.tabs.query({ active: true, windowType: 'normal' })).map((t) => t.windowId + ':' + t.id).sort());
await a.bringToFront(); await a.waitForTimeout(600);
const before = await actives();
await T.tap(a);
const f = () => T.frame(a);
T.log('the window list appears on the left', (await f().$$eval('#wins .win', (x) => x.length)) === 3);
await a.keyboard.down('Alt'); await a.keyboard.press('KeyW'); await a.keyboard.up('Alt'); await a.waitForTimeout(300);
T.log('Alt+W narrows to one window', (await f().$$eval('#wins .win[aria-pressed="true"]', (x) => x.map((n) => n.textContent)))[0].startsWith('This window'));
await a.keyboard.down('Alt'); await a.keyboard.press('KeyW'); await a.keyboard.up('Alt'); await a.waitForTimeout(300);
const only = await f().$$eval('#open-grid .card', (x) => x.length);
T.log('the filter changes what is shown', only === 3, String(only));
const sweepLabel = () => f().$eval('#sweep-btn', (n) => (n.hidden ? '' : n.textContent.trim()));
const scoped = await sweepLabel();
T.log('capture button follows the window filter', /^2 without preview · Capture these/.test(scoped), scoped);
await a.keyboard.down('Alt'); await a.keyboard.press('KeyW'); await a.keyboard.up('Alt'); await a.waitForTimeout(300);
const label = await sweepLabel();
T.log('capture button counts tabs in both windows', /^4 without preview · Capture all/.test(label), label);
await f().click('#sweep-btn');
await wait(9000);
const after = await actives();
T.log('each window is back on the tab it showed', JSON.stringify(before) === JSON.stringify(after), JSON.stringify([before, after]));
const idx = await ev(() => chrome.storage.local.get('pvidx').then((o) => Object.keys(o.pvidx || {}).map((u) => u.split('/').pop()).sort()));
T.log('all six pages have previews', ['alpha', 'beta', 'gamma', 'delta', 't1', 't2'].every((n) => idx.includes(n + '.html')), idx.join());
const focus = await ev(async () => (await chrome.windows.getLastFocused()).id);
T.log('the first window has focus again', focus !== w2);
await T.close();
