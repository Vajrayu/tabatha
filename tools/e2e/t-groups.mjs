// Tab groups: sections, saved copies surviving a closed group / window, reopen, two-step removal, MRU selection.
import { launch, withTabGroups } from './lib.mjs';
const T = await launch(withTabGroups(process.env.EXT));
const ev = (fn, arg) => T.sw.evaluate(fn, arg);
const saved = () => ev(() => chrome.storage.local.get('groups').then((o) => o.groups || []));
const [a, b, c, d] = await T.open(['alpha', 'beta', 'gamma', 'delta']); await T.skipFirstRun();
const ids = await ev(async () => (await chrome.tabs.query({})).map((t) => ({ id: t.id, title: t.title })));
const idOf = (n) => ids.find((x) => x.title.includes(n)).id;
await ev(async ([x, y]) => { const g = await chrome.tabs.group({ tabIds: [x, y] }); await chrome.tabGroups.update(g, { title: 'Research', color: 'blue' }); }, [idOf('alpha'), idOf('beta')]);
await c.waitForTimeout(1500);
let s = await saved();
T.log('a live group is saved while open', s.length === 1 && s[0].open && s[0].title === 'Research' && s[0].tabs.length === 2);
await c.bringToFront(); await T.tap(c);
const f = () => T.frame(c);
T.log('group shows as a section with its name', (await f().$$eval('.gsec.grouped', (x) => x.length)) === 1 && (await f().$eval('.gsec.grouped .ghead', (n) => n.textContent)).startsWith('Research'));
T.log('ungrouped tabs sit under their own header', (await f().$eval('.gsec:not(.grouped) .ghead', (n) => n.textContent)).startsWith('Ungrouped'));
T.log('opens on the previous tab (MRU), not the first card', (await f().$eval('.card[aria-selected="true"] .title', (n) => n.textContent)) === 'delta page');
await c.keyboard.press('Escape'); await c.waitForTimeout(300);
await ev(async ([x, y]) => chrome.tabs.remove([x, y]), [idOf('alpha'), idOf('beta')]);
await c.waitForTimeout(1500);
s = await saved();
T.log('a closed group is kept with its tabs', s.length === 1 && !s[0].open && s[0].tabs.length === 2);
await T.tap(c);
T.log('it shows under Saved tab groups', (await f().$$eval('#saved-grid .card', (x) => x.length)) === 1);
T.log('its tabs are not repeated under Recently closed', (await f().$$eval('#closed-grid .card', (x) => x.length)) === 0);
await f().click('#saved-grid .card'); await c.waitForTimeout(1500);
const now = await ev(async () => { const g = await chrome.tabGroups.query({}); const t = await chrome.tabs.query({}); return { groups: g.map((x) => [x.title, x.color]), inGroup: t.filter((x) => x.groupId >= 0).length }; });
T.log('reopening recreates a real group (name, colour, tabs)', now.groups.length === 1 && now.groups[0][0] === 'Research' && now.groups[0][1] === 'blue' && now.inGroup === 2, JSON.stringify(now));
s = await saved(); T.log('the same record is live again', s.length === 1 && s[0].open);
const w2 = await ev(async () => { const t = await chrome.tabs.query({}); const w = await chrome.windows.create({ url: t.find((x) => x.groupId >= 0).url }); const g = await chrome.tabs.group({ tabIds: [(await chrome.tabs.query({ windowId: w.id }))[0].id], createProperties: { windowId: w.id } }); await chrome.tabGroups.update(g, { title: 'Doomed', color: 'red' }); return w.id; });
await c.waitForTimeout(1500); await ev(async (w) => chrome.windows.remove(w), w2); await c.waitForTimeout(1500);
s = await saved(); const doomed = s.find((g) => g.title === 'Doomed');
T.log('a group survives its window being closed', !!doomed && !doomed.open);
await c.bringToFront(); await T.tap(c);
const idx = (await f().$$eval('#saved-grid .card', (x) => x.map((n) => n.querySelector('.title').textContent))).indexOf('Doomed');
await c.mouse.move(600, 500); await c.mouse.move(640, 520);
await f().hover(`#saved-grid .card:nth-child(${idx + 1})`); await c.waitForTimeout(200);
await c.keyboard.press('Delete'); await c.waitForTimeout(300);
T.log('first Delete only asks', (await saved()).some((g) => g.title === 'Doomed') && (await f().$$eval('.gcard.armed', (x) => x.length)) === 1);
await c.keyboard.press('Delete'); await c.waitForTimeout(400);
T.log('second Delete removes it, and only it', !(await saved()).some((g) => g.title === 'Doomed') && (await saved()).some((g) => g.title === 'Research'));
await T.close();
