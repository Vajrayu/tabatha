// The review reminder: quiet banner, then one dialog, never repeated too soon, ends when answered.
import { launch } from './lib.mjs';
const T = await launch(process.env.EXT);
const ls = (k) => T.sw.evaluate((k) => chrome.storage.local.get(k).then((o) => o[k]), k);
const setRv = (o) => T.sw.evaluate((o) => chrome.storage.local.set({ rv: o }), o);
const [c] = await T.open(['alpha']); await T.skipFirstRun();
const f = () => T.frame(c);
const day = 86400000, now = Date.now();
await T.tap(c); await c.keyboard.press('Escape'); await c.waitForTimeout(300);
T.log('open counter counts', (await ls('rv')).opens >= 1);
await setRv({ since: now - 20 * day, opens: 20, soft: 0, lastSoft: 0, asks: 0, lastAsk: 0, done: false });
await T.tap(c); await c.waitForTimeout(400);
T.log('quiet banner after 20 opens (and no dialog)', !(await f().$eval('#soft', (n) => n.hidden)) && (await f().$eval('#modal', (n) => n.hidden)));
await f().click('#soft-later'); await c.keyboard.press('Escape'); await c.waitForTimeout(300);
await T.tap(c); await c.waitForTimeout(400);
T.log('not shown again straight away', await f().$eval('#soft', (n) => n.hidden));
await c.keyboard.press('Escape'); await c.waitForTimeout(300);
await setRv({ since: now - 20 * day, opens: 60, soft: 3, lastSoft: now - 5 * day, asks: 0, lastAsk: 0, done: false });
await T.tap(c); await c.waitForTimeout(700);
T.log('dialog after 3 banners', !(await f().$eval('#modal', (n) => n.hidden)));
T.log('asks how it is going', (await f().$eval('#dlg-title', (n) => n.textContent)) === 'How is Tabatha working for you?');
await f().click('text=Needs work'); await c.waitForTimeout(250);
const btns = await f().$$eval('#dialog button', (x) => x.map((b) => b.textContent));
T.log('a bad answer still offers the review button, plus feedback', btns.some((x) => /Review on the Chrome Web Store/.test(x)) && btns.includes('Tell me what to fix'), btns.join('|'));
await c.keyboard.press('Escape'); await c.waitForTimeout(250);
T.log('Esc closes the dialog only', (await T.isOpen(c)) && (await f().$eval('#modal', (n) => n.hidden)));
T.log('dialog counted', (await ls('rv')).asks === 1);
await c.keyboard.press('Escape'); await c.waitForTimeout(300);
await setRv({ since: now - 20 * day, opens: 60, soft: 3, lastSoft: now - 5 * day, asks: 1, lastAsk: now - day, done: false });
await T.tap(c); await c.waitForTimeout(600);
T.log('dialog not repeated within 14 days', await f().$eval('#modal', (n) => n.hidden));
await c.keyboard.press('Escape'); await c.waitForTimeout(300);
await setRv({ since: now - 20 * day, opens: 25, soft: 0, lastSoft: 0, asks: 0, lastAsk: 0, done: false });
await T.tap(c); await c.waitForTimeout(400);
const softShown = !(await f().$eval('#soft', (n) => n.hidden));
await f().click('#soft-review'); await c.waitForTimeout(900);
if (!softShown) console.log('DEBUG banner was not shown');
const urls = await T.sw.evaluate(async () => (await chrome.tabs.query({})).map((t) => t.url || t.pendingUrl));
T.log('review click opens the store reviews page', urls.some((u) => /chromewebstore\.google\.com\/detail\/(tabatha\/)?edjglhlabdmgacehahfdjjffapbkaekk\/reviews/.test(u)), JSON.stringify({ urls, rv: await ls('rv') }));
T.log('and it never asks again', (await ls('rv')).done === true);
await T.close();
